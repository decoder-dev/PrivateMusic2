/// Minimal synthetic AAC pipeline that produces raw AAC bytes for tests.
/// The bytes are deterministic, non-copyrighted, and represent a tiny
/// 440 Hz sine tone at 44.1 kHz stereo.
enum FragmentedMP4Fixture {
    struct Bundle {
        let initialization: Data
        let fragments: [Data]
    }

    static func make() throws -> Bundle {
        // We can't reliably generate real CMAF files from the simulator,
        // so use a pre-built data pack. This keeps tests deterministic and
        // independent of AVAssetWriter quirks on CI.
        return try Bundle(
            initialization: Data(Self.initBytes),
            fragments: [
                Data(Self.segment1Bytes),
                Data(Self.segment2Bytes)
            ]
        )
    }

    private enum FixtureError: Error {
        case unsupportedPlatform
    }

